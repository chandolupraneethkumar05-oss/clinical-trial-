"""
ProtocolShield Cohort Simulation API Routes
"""
import logging
from typing import Optional
from fastapi import APIRouter, HTTPException, Query, Depends
from app.models.patient import CohortFilterCriteria
from app.engine.synthetic_data import seed_database_if_empty, generate_synthetic_cohort
from app.engine.cohort_simulator import cohort_engine
from app.db.duckdb_client import db_client
from app.core.security import require_role, AuthenticatedUser

router = APIRouter(prefix="/cohort", tags=["Cohort Simulation"])
logger = logging.getLogger(__name__)

SYNTHETIC_DISCLAIMER = (
    "This dataset contains entirely synthetic patient records generated by statistical simulation. "
    "It does not represent real patients, clinical outcomes, or actual trial data. "
    "For research and planning purposes only."
)


@router.get("/stats")
async def get_cohort_statistics(
    _user: AuthenticatedUser = Depends(require_role(["doctor", "admin"]))
):
    """Returns overview statistics of the synthetic patient population. Requires doctor or admin role."""
    try:
        count = db_client.count_patients()
        if count == 0:
            count = seed_database_if_empty(10000)

        conn = db_client.get_connection()
        try:
            stage_dist = conn.execute(
                "SELECT cancer_stage, count(*) as count FROM patients GROUP BY cancer_stage ORDER BY count DESC"
            ).fetchall()
            
            ecog_dist = conn.execute(
                "SELECT ecog_score, count(*) as count FROM patients GROUP BY ecog_score ORDER BY ecog_score"
            ).fetchall()

            rurality_dist = conn.execute(
                "SELECT rurality, count(*) as count FROM patients GROUP BY rurality ORDER BY count DESC"
            ).fetchall()

            avg_metrics = conn.execute("""
                SELECT 
                    round(avg(age), 1) as avg_age,
                    round(avg(egfr_ml_min), 1) as avg_egfr,
                    round(avg(distance_to_center_miles), 1) as avg_distance_miles,
                    round(avg(anc), 0) as avg_anc
                FROM patients
            """).fetchone()

            return {
                "is_synthetic_data": True,
                "data_disclaimer": SYNTHETIC_DISCLAIMER,
                "total_patients": count,
                "stages": [{"stage": s, "count": c} for s, c in stage_dist],
                "ecog_scores": [{"ecog": e, "count": c} for e, c in ecog_dist],
                "rurality": [{"type": r, "count": c} for r, c in rurality_dist],
                "averages": {
                    "age": avg_metrics[0],
                    "egfr": avg_metrics[1],
                    "distance_miles": avg_metrics[2],
                    "anc": avg_metrics[3]
                }
            }
        finally:
            conn.close()
    except HTTPException:
        raise
    except Exception:
        logger.exception("Failed to retrieve cohort statistics")
        raise HTTPException(status_code=500, detail="An unexpected error occurred retrieving cohort statistics.")


REGENERATION_CONFIRM_TOKEN = "CONFIRM_REGENERATE_SYNTHETIC_COHORT"


@router.post("/seed")
async def seed_cohort(
    total: int = Query(default=10000, ge=100, le=50000),
    force_regenerate: bool = Query(
        default=False,
        description="When False (default), seeds ONLY if cohort has fewer than 'total' records (never deletes existing data).",
    ),
    confirm_regenerate: Optional[str] = Query(
        default=None,
        description=f"Required confirmation string ('{REGENERATION_CONFIRM_TOKEN}') when force_regenerate=True.",
    ),
    _user: AuthenticatedUser = Depends(require_role(["admin"])),
):
    """
    Seeds synthetic cohort records if the database is empty or below 'total' (seed-if-empty behavior).
    To protect against accidental data loss, existing records are preserved unless BOTH
    force_regenerate=True AND confirm_regenerate='CONFIRM_REGENERATE_SYNTHETIC_COHORT' are supplied.
    Requires administrator role.
    """
    try:
        if force_regenerate:
            if confirm_regenerate != REGENERATION_CONFIRM_TOKEN:
                raise HTTPException(
                    status_code=400,
                    detail=(
                        "Regenerating the synthetic cohort deletes and replaces existing cohort records. "
                        f"Pass confirm_regenerate='{REGENERATION_CONFIRM_TOKEN}' to proceed."
                    ),
                )
            df = generate_synthetic_cohort(total_patients=total)
            with db_client.transaction() as conn:
                conn.execute("DELETE FROM patients")
                conn.register("df_regen", df)
                conn.execute("INSERT INTO patients SELECT * FROM df_regen")
                row = conn.execute("SELECT count(*) FROM patients").fetchone()
                count = int(row[0]) if row else 0
            try:
                from app.api.routes_audit import record_audit_event
                record_audit_event(
                    user_id=_user.id,
                    user_name=_user.name,
                    user_role=_user.role,
                    action="COHORT_SYNTHETIC_REGENERATE",
                    resource_type="COHORT",
                    resource_id="patients",
                    details=f"Administrator explicitly regenerated synthetic cohort with {count} records.",
                )
            except Exception:
                logger.exception("Failed to record audit event for cohort regeneration")

            return {
                "status": "success",
                "mode": "regenerated",
                "regenerated": True,
                "existing_records_preserved": False,
                "total_records": count,
                "message": f"Synthetic cohort explicitly regenerated with {count} records.",
                "is_synthetic_data": True,
                "data_disclaimer": SYNTHETIC_DISCLAIMER,
            }

        existing_count = db_client.count_patients()
        count = seed_database_if_empty(total_patients=total)
        seeded_new = count > existing_count
        return {
            "status": "success",
            "mode": "seeded_if_empty" if seeded_new else "already_populated",
            "regenerated": False,
            "existing_records_preserved": True,
            "total_records": count,
            "message": (
                f"Seeded synthetic cohort to {count} records."
                if seeded_new
                else f"Cohort already contains {count} records; existing data preserved (seed-if-empty mode)."
            ),
            "is_synthetic_data": True,
            "data_disclaimer": SYNTHETIC_DISCLAIMER,
        }
    except HTTPException:
        raise
    except Exception:
        logger.exception("Failed to seed cohort database")
        raise HTTPException(status_code=500, detail="An unexpected error occurred seeding the cohort database.")


@router.post("/simulate-funnel")
async def simulate_funnel(
    criteria: CohortFilterCriteria,
    _user: AuthenticatedUser = Depends(require_role(["doctor", "admin"]))
):
    """
    Executes vectorized multi-stage funnel filtering across the 10,000 synthetic cohort
    and identifies parameter sensitivity bottlenecks. Requires doctor or admin role.
    """
    try:
        # Auto-seed if not seeded yet
        if db_client.count_patients() == 0:
            seed_database_if_empty(10000)

        results = cohort_engine.simulate_eligibility_funnel(criteria)
        if isinstance(results, dict):
            results["is_synthetic_data"] = True
            results["data_disclaimer"] = SYNTHETIC_DISCLAIMER
        return results
    except HTTPException:
        raise
    except Exception:
        logger.exception("Cohort funnel simulation failed")
        raise HTTPException(status_code=500, detail="An unexpected error occurred during cohort funnel simulation.")


@router.api_route("/retention-curve", methods=["GET", "POST"])
async def calculate_retention_curve(
    enrolled_size: int = Query(default=400, ge=10, le=10000),
    composite_pbi: float = Query(default=62.5, ge=0.0, le=100.0),
    duration_weeks: int = Query(default=52, ge=4, le=104),
    peak_weeks: list[int] = Query(default=[1, 6, 12, 24]),
    _user: AuthenticatedUser = Depends(require_role(["doctor", "admin"]))
):
    """
    Calculates week-by-week patient retention and hazard curve over trial duration.
    Requires doctor or admin role.
    """
    try:
        curve = cohort_engine.simulate_longitudinal_retention(
            enrolled_cohort_size=enrolled_size,
            composite_pbi=composite_pbi,
            study_duration_weeks=duration_weeks,
            peak_burden_weeks=peak_weeks
        )
        return {
            "retention_curve": curve,
            "is_synthetic_data": True,
            "data_disclaimer": SYNTHETIC_DISCLAIMER
        }
    except HTTPException:
        raise
    except Exception:
        logger.exception("Retention curve calculation failed")
        raise HTTPException(status_code=500, detail="An unexpected error occurred calculating the retention curve.")

