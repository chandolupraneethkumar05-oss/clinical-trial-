class PatientScreeningInput(BaseModel):
    patient_id: Optional[str] = Field(default="PT-EVAL-2026", max_length=120)
    data_provenance: Optional[str] = Field(
        default=None,
        description="Optional client hint ('synthetic_demo' | 'patient_reported' | 'unknown'); server enforces authoritative provenance",
    )
    is_demo_profile: bool = Field(
        default=False,
        description="Set true only when screening synthetic demonstration profile data",
    )
    investigator_verified: bool = Field(
        default=False,
        description="Honored exclusively for authenticated doctor or admin callers",
    )
    age: int = Field(..., ge=18, le=95, description="Required patient age in years (18-95)")
    gender: Optional[str] = Field(default=None, max_length=40)
    primary_cancer_type: Optional[str] = Field(default=None, max_length=120)
    cancer_stage: str = Field(..., min_length=1, max_length=100, description="Required cancer stage")
    ecog_score: int = Field(..., ge=0, le=4, description="Required ECOG performance status (0-4)")
    egfr_ml_min: float = Field(..., ge=10.0, le=150.0, description="Required eGFR in mL/min/1.73m2")
    anc: Optional[float] = Field(default=None, ge=100.0, le=100000.0, description="Absolute Neutrophil Count cells/uL")
    platelets: Optional[float] = Field(default=None, ge=10.0, le=5000.0, description="Platelets x10^3/uL")
    hemoglobin: Optional[float] = Field(default=None, ge=5.0, le=25.0, description="Hemoglobin g/dL")
    total_bilirubin: Optional[float] = Field(default=None, ge=0.1, le=20.0, description="Total Bilirubin mg/dL")
    alt_u_l: Optional[float] = Field(default=None, ge=5.0, le=2000.0, description="ALT U/L")
    prior_lines: Optional[int] = Field(default=None, ge=0, le=10)
    has_active_brain_mets: Optional[bool] = None
    has_stable_brain_mets: Optional[bool] = None
    has_active_autoimmune: Optional[bool] = None
    has_egfr_sensitizing_mutation: Optional[bool] = None
    has_her2_positive: Optional[bool] = None
    has_hormone_receptor_positive: Optional[bool] = None
    has_bcma_positive: Optional[bool] = None
    pdl1_tps_percent: Optional[float] = Field(default=None, ge=0.0, le=100.0)
    distance_to_center_miles: Optional[float] = Field(default=None, ge=1.0, le=500.0)

    @field_validator("cancer_stage")
    @classmethod
    def validate_cancer_stage(cls, v: str) -> str:
        cleaned = v.strip()
        if not cleaned:
            raise ValueError("cancer_stage must not be blank.")
        return cleaned

    @field_validator(
        "egfr_ml_min",
        "anc",
        "platelets",
        "hemoglobin",
        "total_bilirubin",
        "alt_u_l",
        "pdl1_tps_percent",
        "distance_to_center_miles",
    )
    @classmethod
    def validate_finite_floats(cls, v: Optional[float], info) -> Optional[float]:
        if v is not None and not math.isfinite(v):
            raise ValueError(f"{info.field_name} must be a finite numeric value.")
        return v


